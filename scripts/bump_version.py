#!/usr/bin/env python3
"""Bump version and create git tag.

Usage:
  python scripts/bump_version.py patch   # 0.3.5 → 0.3.6
  python scripts/bump_version.py minor   # 0.3.5 → 0.4.0
  python scripts/bump_version.py major   # 0.3.5 → 1.0.0
"""

import re
import subprocess
import sys
from pathlib import Path


def read_version() -> str:
    pyproject = Path("pyproject.toml").read_text(encoding="utf-8")
    m = re.search(r'^version\s*=\s*"([^"]+)"', pyproject, re.MULTILINE)
    if not m:
        raise RuntimeError("version not found in pyproject.toml")
    return m.group(1)


def write_version(new_version: str) -> None:
    path = Path("pyproject.toml")
    old = path.read_text(encoding="utf-8")
    updated = re.sub(
        r'^(version\s*=\s*)"([^"]+)"',
        lambda m: f'{m.group(1)}"{new_version}"',
        old,
        count=1,
        flags=re.MULTILINE,
    )
    path.write_text(updated, encoding="utf-8")
    print(f"  pyproject.toml: {read_version()}")


def bump(part: str) -> str:
    parts = [int(x) for x in read_version().split(".")]
    if part == "major":
        parts = [parts[0] + 1, 0, 0]
    elif part == "minor":
        parts = [parts[0], parts[1] + 1, 0]
    elif part == "patch":
        parts = [parts[0], parts[1], parts[2] + 1]
    else:
        raise ValueError(f"Unknown part: {part}")
    return ".".join(str(x) for x in parts)


def update_changelog(version: str) -> None:
    changelog = Path("CHANGELOG.md")
    if not changelog.exists():
        return
    old = changelog.read_text(encoding="utf-8")
    # Insert a new entry after the header
    lines = old.split("\n")
    insert = [
        f"## v{version} (UNDATED) — WIP",
        "",
        "> Generated by bump_version.py",
        "",
        "---",
        "",
    ]
    # Find first existing version header and insert before it
    for i, line in enumerate(lines):
        if line.startswith("## v") and "WIP" not in line:
            lines = lines[:i] + insert + lines[i:]
            break
    changelog.write_text("\n".join(lines), encoding="utf-8")
    print(f"  CHANGELOG.md: v{version} entry added")


def git_commit_tag(version: str, message: str) -> None:
    subprocess.run(["git", "add", "pyproject.toml", "CHANGELOG.md"], check=True)
    subprocess.run(
        ["git", "commit", "-m", f"release: v{version}\n\n{message}"],
        check=True,
    )
    subprocess.run(["git", "tag", "-a", f"v{version}", "-m", f"v{version}"], check=True)
    print(f"  git tag v{version} created")
    print(f"\nNext: git push origin main --tags")


def main() -> None:
    if len(sys.argv) < 2 or sys.argv[1] not in ("patch", "minor", "major"):
        print(__doc__.strip())
        sys.exit(1)

    part = sys.argv[1]
    old_ver = read_version()
    new_ver = bump(part)
    message = " ".join(sys.argv[2:]) or f"Bump version: {old_ver} → {new_ver}"

    print(f"Version: {old_ver} → {new_ver} ({part})")
    print()

    write_version(new_ver)
    update_changelog(new_ver)
    git_commit_tag(new_ver, message)

    print("\nDone.")


if __name__ == "__main__":
    main()
